import type { GitHubProfilePayload, GitHubCommitData, CommitCategory } from '../domain/city/types';

function makeCommits(
  seedPrefix: string,
  author: string,
  items: { msg: string; daysAgo: number; cat: CommitCategory }[]
): GitHubCommitData[] {
  const now = Date.now();
  return items.map((item, idx) => {
    const hash = Math.abs(
      Array.from(`${seedPrefix}-${idx}-${item.msg}`).reduce((a, ch) => ((a << 5) - a + ch.charCodeAt(0)) | 0, 0)
    )
      .toString(16)
      .padStart(8, '0');
    return {
      sha: `${hash}${idx.toString(16).padStart(4, '0')}`.slice(0, 12),
      message: item.msg,
      date: new Date(now - item.daysAgo * 86400000).toISOString(),
      authorName: author,
      authorLogin: author.toLowerCase().replace(/\s+/g, ''),
      category: item.cat,
    };
  });
}

function daysAgoIso(days: number): string {
  return new Date(Date.now() - days * 86400000).toISOString();
}

